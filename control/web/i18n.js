const messages = catalogs;

function placeholders(value) {
  return [...String(value).matchAll(/\{([a-zA-Z0-9_]+)\}/g)].map(match => match[1]).sort();
}

function validateCatalogs() {
  const baseKeys = Object.keys(messages.de).sort();
  for (const language of SUPPORTED_LANGUAGES) {
    const table = messages[language];
    if (!table || typeof table !== 'object') throw new Error(`Missing translation catalog: ${language}`);
    const keys = Object.keys(table).sort();
    if (keys.length !== baseKeys.length || keys.some((key, index) => key !== baseKeys[index])) {
      throw new Error(`Translation catalog key mismatch: ${language}`);
    }
    for (const key of baseKeys) {
      if (typeof table[key] !== 'string' || table[key].trim() === '') throw new Error(`Empty translation: ${language}:${key}`);
      const expected = placeholders(messages.de[key]);
      const actual = placeholders(table[key]);
      if (expected.length !== actual.length || expected.some((token, index) => token !== actual[index])) {
        throw new Error(`Translation placeholder mismatch: ${language}:${key}`);
      }
    }
  }
}

